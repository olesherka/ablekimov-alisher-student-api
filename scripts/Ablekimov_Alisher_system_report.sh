#!/bin/bash
# =============================================================
# System report script
# Author: Ablekimov Alisher (ID 37637, group IT2-2312)
# Shows system information and saves it to the personal log file.
# Usage: ./scripts/Ablekimov_Alisher_system_report.sh
# =============================================================

STUDENT_NAME="Ablekimov Alisher"
STUDENT_ID="37637"
STUDENT_GROUP="IT2-2312"

# Find the project folder (the parent of the scripts/ folder),
# so the script works no matter where it is started from
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
LOG_DIR="$PROJECT_DIR/logs"
LOG_FILE="$LOG_DIR/Ablekimov_Alisher_system_report.log"

mkdir -p "$LOG_DIR"

# Everything inside { } is shown on screen AND appended to the log (tee -a)
{
    echo "============================================================"
    echo " SYSTEM REPORT"
    echo "============================================================"
    echo "Student full name : $STUDENT_NAME"
    echo "Student ID / group: $STUDENT_ID / $STUDENT_GROUP"
    echo "Date and time     : $(date '+%Y-%m-%d %H:%M:%S %Z')"
    echo "Current user      : $(whoami)"
    echo "Hostname          : $(hostname)"
    echo

    echo "---------------- Operating system ----------------"
    if [ -f /etc/os-release ]; then
        . /etc/os-release
        echo "OS                : $PRETTY_NAME"
    else
        echo "OS                : $(uname -s)"
    fi
    echo "Kernel version    : $(uname -r)"
    echo "Architecture      : $(uname -m)"
    echo

    echo "---------------- CPU ----------------"
    if command -v lscpu > /dev/null 2>&1; then
        lscpu | grep -E "^(Model name|CPU\(s\)|Thread\(s\) per core|Core\(s\) per socket)"
    else
        grep -m1 "model name" /proc/cpuinfo
        echo "CPU cores: $(nproc)"
    fi
    echo

    echo "---------------- Memory ----------------"
    free -h
    echo

    echo "---------------- Disk usage ----------------"
    df -h -x tmpfs -x devtmpfs 2>/dev/null || df -h
    echo

    echo "---------------- Available disk space ----------------"
    echo "Available on / (root) : $(df -h / | awk 'NR==2 {print $4}') of $(df -h / | awk 'NR==2 {print $2}')"
    echo "Available in project  : $(df -h "$PROJECT_DIR" | awk 'NR==2 {print $4}')"
    echo
    echo "Report generated by $STUDENT_NAME"
    echo "============================================================"
    echo
} | tee -a "$LOG_FILE"

echo "Report saved to: $LOG_FILE"
